def _wk_sv(w) -> str:
    if not w:
        return "?"
    return f"{w[0]} tentaperiod" if w[1] == 0 else f"{w[0]} v{w[1]}"


def sequence_sv(hunks: list[dict], limit: int = 4) -> str:
    """Swedish description of structure.sequence_hunks (from issue details)."""
    from ..checks.structure import describe_hunks
    return "; ".join(describe_hunks(hunks, limit, label=_wk_sv)).replace("… and", "… och").replace(" more", " till")


def _relation_text(lang: str, rel: str, scope: str) -> str:
    t = T[lang]["rel"]
    if not rel:
        return ""
    base = rel.split(":reexam")[0]
    if base.startswith("eligibility:"):
        return t["eligibility"].format(m=base.split(":", 1)[1])
    if base.startswith("retake:"):
        _, c, y = base.split(":")
        return t["retake"].format(scope=scope, c=c, y=y)
    return t.get(base, "")


def _exam_pair(i: Issue, lang: str) -> str:
    d = i.details
    t = T[lang]
    a, b = d["courses"]
    ka, kb = (t["kind"][k] for k in d["kinds"])
    gap = t["overlap"] if d.get("why") == "overlapping" else t["gap"].get(d["gap_days"], "")
    rel = _relation_text(lang, d.get("relation", ""), i.scope)
    if lang == "sv":
        s = (f"{a} ({ka} {d['dates'][0]} {d['times'][0]}) och {b} ({kb} {d['dates'][1]} "
             f"{d['times'][1]}) ligger {gap}.")
    else:
        s = (f"{a} ({ka} {d['dates'][0]} {d['times'][0]}) and {b} ({kb} {d['dates'][1]} "
             f"{d['times'][1]}) are scheduled {gap}.")
    return f"{s} {rel} {t['ask_move']}".strip()


def _teaching(i: Issue, lang: str) -> str:
    d = i.details
    a, b = d["courses"]
    rel = _relation_text(lang, d.get("relation", ""), i.scope)
    sess = "; ".join(f"{s['date']} {s['times'][0]} {s['activities'][0]} / {s['times'][1]} {s['activities'][1]}"
                     for s in d["sessions"][:4])
    more = len(d["sessions"]) - 4
    ref, n_old = d.get("reference_term"), d.get("reference_count", 0)
    if lang == "sv":
        s = f"{a} och {b} har {d['count']} tillfälle(n) som krockar: {sess}"
        s += f" (+{more} till)." if more > 0 else "."
        if ref:
            s += f" {ref}: {n_old} krock(ar)." if n_old else f" Inga krockar {ref}."
        return f"{s} {rel} Går det att flytta?".strip()
    s = f"{a} and {b} have {d['count']} overlapping session(s): {sess}"
    s += f" (+{more} more)." if more > 0 else "."
    if ref:
        s += f" {ref}: {n_old} overlap(s)." if n_old else f" No overlaps in {ref}."
    return f"{s} {rel} Could one be moved?".strip()


def render_issue(i: Issue, lang: str) -> str:
    t = T[lang]
    d = i.details
    ref = d.get("reference_term", "")
    if i.check == "teaching.overlap" and "sessions" in d:
        return _teaching(i, lang)
    if i.check == "teaching.self-overlap" and "sessions" in d:
        sess = "; ".join(f"{x['date']} {x['times'][0]} {x['activities'][0]} / {x['times'][1]} "
                         f"{x['activities'][1]}" for x in d["sessions"][:4])
        n_old = d.get("reference_count", 0)
        if lang == "sv":
            s = f"{i.course} krockar med sig själv: {sess}."
            if d.get("both_whole_class"):
                s += (" Båda tillfällena är markerade som helklass – ska studenterna vara på båda, "
                      "eller ska de delas i grupper?")
            if ref:
                s += f" Samma mönster fanns {ref}." if n_old else f" Fanns inte {ref}."
            return s
        return f"{i.message} Should these be split into groups, or moved?"
    if i.check in ("exams.spacing", "exams.reexam-path") and "courses" in d:
        return _exam_pair(i, lang)
    if lang == "sv":
        if i.check == "coverage.missing-course":
            return (f"{i.course} {d.get('name', '')} ingår i utbildningsplanen för {i.scope} "
                    f"({', '.join(d.get('periods', []))}) men finns inte i schemat.")
        if i.check in ("coverage.missing-exam", "coverage.missing-reexam", "structure.exam-gone"):
            why = []
            if d.get("plan_exam_periods"):
                why.append(f"utbildningsplanen har tentamen i {'/'.join(d['plan_exam_periods'])}")
            if d.get("reference_ordinary") and i.check != "coverage.missing-reexam":
                why.append(f"{ref} fanns ordinarie tentamen ({'; '.join(d['reference_ordinary'])})")
            if d.get("reference_reexam") and i.check == "coverage.missing-reexam":
                why.append(f"{ref} fanns omtentamen ({'; '.join(d['reference_reexam'])})")
            if d.get("syllabus_written"):
                why.append(f"kursplanen (giltig från {d['syllabus_valid_from']}) har "
                           + ", ".join(d["syllabus_written"]))
            what = "ingen omtentamen är schemalagd" if i.check == "coverage.missing-reexam" \
                else "ordinarie tentamen saknas i tentamensperioden"
            return f"{i.course}: {what}" + (f" – {'; '.join(why)}" if why else "") + ". Ska den läggas in?"
        if i.check == "syllabus.unknown-module":
            return (f"{i.course}: tentamen är registrerad som {', '.join(d.get('scheduled', []))}, men den "
                    f"gällande kursplanen (från {d.get('syllabus_valid_from')}) har modulerna "
                    f"{', '.join(d.get('syllabus_modules', []))}. Ska modulen ändras?")
        if i.check == "syllabus.module-not-scheduled":
            return (f"{i.course}: kursplanen (från {d.get('syllabus_valid_from')}) har "
                    f"{', '.join(d.get('missing', []))}, men ingen schemalagd tentamen anger den "
                    f"(schemalagt: {', '.join(d.get('scheduled', []))}). Ska den läggas in?")
        if i.check == "coverage.group-empty":
            return f"Ingen kurs i gruppen '{i.key}' är schemalagd för {i.scope}."
        if i.check == "coverage.no-plan":
            return i.message
        if i.check == "structure.counts":
            ch = "; ".join(f"{a} {o}→{n}" for a, (o, n) in d.get("counts", {}).items() if o != n)
            det = sequence_sv(d.get("sequence", []))
            return (f"{i.course}: antalet tillfällen skiljer sig från {ref} ({ch})."
                    + (f" Sekvens ({ref} → nu): {det}." if det else "") + f" {t['ask_intended']}")
        if i.check == "structure.order":
            return (f"{i.course}: samma tillfällen som {ref} men i annan ordning "
                    f"({ref} → nu: {sequence_sv(d.get('sequence', []))}). {t['ask_intended']}")
        if i.check == "structure.week-shift":
            moved = i.message.split("weeks: ", 1)[-1].rstrip(".")
            return (f"{i.course}: tillfällen har flyttats minst två undervisningsveckor jämfört med {ref} "
                    f"({moved}). {t['ask_intended']}")
        if i.check == "structure.course-gone":
            return f"{i.course} hade undervisning {ref} men saknar undervisning i detta schema. {t['ask_intended']}"
        if i.check == "structure.course-new":
            return f"{i.course} är ny jämfört med {ref}. Stämmer det att den ska ingå?"
        if i.check == "structure.exam-modules":
            return (f"{i.course}: examinationsmodulerna på tentamen har ändrats "
                    f"({', '.join(d.get('old', []))} → {', '.join(d.get('new', []))}). {t['ask_intended']}")
        if i.check == "dataquality.round-term":
            return (f"{i.course}: schemaraderna är kopplade till kurstillfälle {i.key}, vilket ser ut "
                    "att vara ett gammalt tillfälle. Ska de kopplas till innevarande tillfälle?")
        if i.check == "dataquality.no-late-reexams":
            return "Exporten verkar inte omfatta omtentaperioden i augusti – kontrollera datumintervallet."
    else:
        if i.check.startswith("structure."):
            return f"{i.message} {t['ask_intended']}"
    return i.message


def render(res: ReviewResult, lang: str = "sv") -> str:
    t = T[lang]
    by_course: dict[str, list[Issue]] = defaultdict(list)
    for i in res.sorted_issues():
        if i.accepted or i.severity not in INCLUDE:
            continue
        by_course[i.course or ""].append(i)

    def order(code):
        worst = min(severity_rank(i.severity) for i in by_course[code])
        return (code == "", worst, code)

    lines = [f"# {t['title']}: {res.title}", "", f"_{t['intro']}_", ""]
    for code in sorted(by_course, key=order):
        lines.append(f"## [{code}](https://www.kth.se/student/kurser/kurs/{code})" if code
                     else f"## {t['general']}")
        lines.append("")
        for i in by_course[code]:
            lines.append(f"- [{i.severity}] {render_issue(i, lang)}")
            for ev in i.evidence[:2]:
                lines.append(f"  - `{ev}`")
        lines.append("")
    return "\n".join(lines)


def write(res: ReviewResult, out_dir: Path, lang: str = "sv") -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    stem = res.title.split(" vs ")[0].replace(", ", "_").replace(" ", "_")
    suffix = "kommentarer" if lang == "sv" else "comments"
    p = out_dir / f"{stem}_{suffix}.md"
    p.write_text(render(res, lang), encoding="utf-8")
    (out_dir / f"{stem}_{suffix}.html").write_text(render_html(res, lang), encoding="utf-8")
    return p


def render_html(res: ReviewResult, lang: str = "sv") -> str:
    """The same drafts as a KTH-styled page (for sharing via a web link).
    Converts the small Markdown subset render() produces."""
    import re
    from .html import CSS, LOGO_SVG, SEV_LABEL, esc, linkify, sev_badge
    md = render(res, lang)
    out, in_list, in_sub = [], False, False
    for line in md.splitlines():
        if line.startswith("# "):
            out.append(f"<div class='kthhead'>{LOGO_SVG}<h1>{esc(line[2:])}</h1></div>")
        elif line.startswith("## "):
            if in_sub: out.append("</ul>"); in_sub = False
            if in_list: out.append("</ul>"); in_list = False
            m = re.match(r"## \[(.+?)\]\((.+?)\)", line)
            out.append(f"<h2><a class='cl' href='{esc(m.group(2))}' target='_blank' rel='noopener'>"
                       f"{esc(m.group(1))}<span class='ext'>↗</span></a></h2>" if m else f"<h2>{esc(line[3:])}</h2>")
        elif line.startswith("- "):
            if in_sub: out.append("</ul>"); in_sub = False
            if not in_list: out.append("<ul class='cm'>"); in_list = True
            m = re.match(r"- \[(\w+)\] (.*)", line)
            sev, text = (m.group(1), m.group(2)) if m else ("", line[2:])
            badge = sev_badge(sev) if sev in SEV_LABEL else esc(sev)
            out.append(f"<li>{badge} {linkify(text)}")
        elif line.startswith("  - "):
            if not in_sub: out.append("<ul class='ev'>"); in_sub = True
            out.append(f"<li><code>{esc(line[4:].strip('`'))}</code></li>")
        elif line.startswith("_") and line.endswith("_"):
            out.append(f"<p class='sub'><em>{esc(line.strip('_'))}</em></p>")
    if in_sub: out.append("</ul>")
    if in_list: out.append("</ul>")
    css = CSS + ".cm { padding-left: 18px; } .cm > li { margin: 6px 0; } .ev { list-style: none; padding-left: 8px; }"
    return ("<!doctype html><html lang='sv'><head><meta charset='utf-8'>"
            "<meta name='viewport' content='width=device-width, initial-scale=1'>"
            "<link rel='stylesheet' href='https://fonts.googleapis.com/css2?family=Figtree:wght@400;500;600;700&display=swap'>"
            f"<title>{esc(T[lang]['title'])}</title><style>{css}</style></head><body><main>"
            + "".join(out) + "</main></body></html>")

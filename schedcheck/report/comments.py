"""Draft remiss comments, grouped per course, in Swedish (default) or English.

These are drafts for a human to edit and send; nothing is sent anywhere.
Only unaccepted issues of severity error/warning/review are included. Each
item is the finding's own text plus its question (Issue.ask), so the drafts
say exactly what the report says.
"""
from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path

from ..i18n import SEVERITY, T
from ..model import Issue, severity_rank
from ..reviews.program import ReviewResult

INCLUDE = ("error", "warning", "review")

TEXT = {
    "title": T("Remisskommentarer (utkast)", "Remiss comments (draft)"),
    "intro": T("Utkast genererat av schedcheck. Granska, stryk det som inte är relevant och "
               "formulera om innan det skickas till schemaläggarna.",
               "Draft generated by schedcheck. Review, remove what is not relevant and rephrase "
               "before sending to the schedulers."),
    "general": T("Övergripande", "General"),
    "schedules": T("Scheman i TimeEdit", "Schedules in TimeEdit"),
    "exported": T("Granskat schema exporterat ur TimeEdit {new}; referens ({ref}) exporterad {old}.",
                  "Reviewed schedule exported from TimeEdit {new}; reference ({ref}) exported {old}."),
    "exported_noref": T("Granskat schema exporterat ur TimeEdit {new}.",
                        "Reviewed schedule exported from TimeEdit {new}."),
}


def render_issue(i: Issue, lang: str) -> str:
    return i.text(lang) + (f" {i.ask[lang]}" if i.ask else "")


def _sev_tag(sev: str, lang: str) -> str:
    return SEVERITY[sev][lang].lower()


def render(res: ReviewResult, lang: str = "sv") -> str:
    t = {k: v[lang] for k, v in TEXT.items()}
    by_course: dict[str, list[Issue]] = defaultdict(list)
    for i in res.sorted_issues():
        if i.accepted or i.severity not in INCLUDE:
            continue
        by_course[i.course or ""].append(i)

    def order(code):
        worst = min(severity_rank(i.severity) for i in by_course[code])
        return (code == "", worst, code)

    lines = [f"# {t['title']}: {res.title}", "", f"_{t['intro']}_", ""]
    from ..io.timeedit import export_time_text
    new_t = export_time_text(res.ctx.new.exports, lang)
    old_t = export_time_text(res.ctx.old.exports, lang) if res.ctx.old else ""
    if new_t:
        lines += [f"_{t['exported'].format(new=new_t, ref=res.ctx.old.term, old=old_t or '?')}_"
                  if res.ctx.old else f"_{t['exported_noref'].format(new=new_t)}_", ""]
    links = [f"[{ex.label} {td.term}]({ex.url})" for td in (res.ctx.new, res.ctx.old) if td
             for ex in sorted(td.exports, key=lambda e: e.label) if ex.url]
    if links:
        lines += [f"{t['schedules']}: " + ", ".join(dict.fromkeys(links)), ""]
    for code in sorted(by_course, key=order):
        lines.append(f"## [{code}](https://www.kth.se/student/kurser/kurs/{code})" if code
                     else f"## {t['general']}")
        lines.append("")
        for i in by_course[code]:
            lines.append(f"- [{_sev_tag(i.severity, lang)}] {render_issue(i, lang)}")
            for ev in i.evidence[:2]:
                lines.append(f"  - `{ev}`")
        lines.append("")
    return "\n".join(lines)


def file_stem(res: ReviewResult, lang: str) -> str:
    stem = res.title.split(" vs ")[0].replace(", ", "_").replace(" ", "_")
    return f"{stem}_{'kommentarer' if lang == 'sv' else 'comments'}"


def write(res: ReviewResult, out_dir: Path, lang: str = "sv") -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    p = out_dir / f"{file_stem(res, lang)}.md"
    p.write_text(render(res, lang), encoding="utf-8")
    (out_dir / f"{file_stem(res, lang)}.html").write_text(render_html(res, lang), encoding="utf-8")
    return p


def render_html(res: ReviewResult, lang: str = "sv") -> str:
    """The same drafts as a KTH-styled page (for sharing via a web link).
    Converts the small Markdown subset render() produces."""
    from .html import CSS, LOGO_SVG, esc, linkify, sev_badge
    tags = {_sev_tag(s, lang): s for s in INCLUDE}
    schedules = TEXT["schedules"][lang]
    md = render(res, lang)
    out, in_list, in_sub = [], False, False
    for line in md.splitlines():
        if line.startswith("# "):
            out.append(f"<div class='kthhead'>{LOGO_SVG}<h1>{esc(line[2:])}</h1></div>")
        elif line.startswith("## "):
            if in_sub: out.append("</ul>"); in_sub = False
            if in_list: out.append("</ul>"); in_list = False
            m = re.match(r"## \[(.+?)\]\((.+?)\)", line)
            out.append(f"<h2><a class='cl' href='{esc(m.group(2))}' target='_blank' rel='noopener'>"
                       f"{esc(m.group(1))}<span class='ext'>↗</span></a></h2>" if m else f"<h2>{esc(line[3:])}</h2>")
        elif line.startswith("- "):
            if in_sub: out.append("</ul>"); in_sub = False
            if not in_list: out.append("<ul class='cm'>"); in_list = True
            m = re.match(r"- \[(\w+)\] (.*)", line)
            sev, text = (tags.get(m.group(1), ""), m.group(2)) if m else ("", line[2:])
            badge = sev_badge(sev, lang) if sev else ""
            out.append(f"<li>{badge} {linkify(text)}")
        elif line.startswith("  - "):
            if not in_sub: out.append("<ul class='ev'>"); in_sub = True
            out.append(f"<li><code>{esc(line[4:].strip('`'))}</code></li>")
        elif line.startswith(schedules + ":"):
            out.append("<p class='sub'>" + re.sub(
                r"\[(.+?)\]\((.+?)\)",
                lambda m: f"<a class='cl' href='{esc(m.group(2))}' target='_blank' rel='noopener'>"
                          f"{esc(m.group(1))}<span class='ext'>↗</span></a>", esc(line)) + "</p>")
        elif line.startswith("_") and line.endswith("_"):
            out.append(f"<p class='sub'><em>{esc(line.strip('_'))}</em></p>")
    if in_sub: out.append("</ul>")
    if in_list: out.append("</ul>")
    css = CSS + ".cm { padding-left: 18px; } .cm > li { margin: 6px 0; } .ev { list-style: none; padding-left: 8px; }"
    return (f"<!doctype html><html lang='{lang}'><head><meta charset='utf-8'>"
            "<meta name='viewport' content='width=device-width, initial-scale=1'>"
            "<link rel='stylesheet' href='https://fonts.googleapis.com/css2?family=Figtree:wght@400;500;600;700&display=swap'>"
            f"<title>{esc(TEXT['title'][lang])}</title><style>{css}</style></head><body><main>"
            + "".join(out) + "</main></body></html>")
